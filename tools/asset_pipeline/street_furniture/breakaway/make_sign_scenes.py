"""Writes <sign>_breakaway.tscn for every knockable sign (Asset Manager; reads the glb log.json files).
python3 make_sign_scenes.py <res_prefix_for_glbs> <res_path_of_breakaway_sign.gd> <out_dir>
Scene: Node3D root -> Base (sign_breakaway_base.glb, visual stub) + Post (RigidBody3D, frozen until hit, breakaway_sign.gd)
-> Model (sign glb) + one BoxShape3D per helper box + HitZone (Area3D, 0.5 m larger than the post, 0-1.5 m)."""
import json, sys, os, glob
pre, gd, out = sys.argv[1], sys.argv[2], sys.argv[3]; os.makedirs(out, exist_ok=True)
here = os.path.dirname(os.path.abspath(__file__)); n = 0
for lp in sorted(glob.glob(os.path.join(here, "..", "mutcd_signs", "sign_*.log.json")) + glob.glob(os.path.join(here, "..", "speed_limit_signs", "sign_*.log.json"))):
    d = json.load(open(lp)); name = d["name"]
    if name == "sign_breakaway_base" or "mass_kg" not in d: continue
    shp = d["proposed_scene_shapes"]; ax = d["anchors_godot_m"]["post_axis_at_ground"]
    L = [f'[gd_scene load_steps={4 + len(shp) + 1} format=3]', "",
         f'; PROPOSAL (Asset Manager) generated by make_sign_scenes.py. Knockable sign per CE 2026-10-09: post ~9 kg + plate = {d["mass_kg"]} kg.',
         '; Frozen (static) until a fast/heavy body enters HitZone, then breaks away (breakaway_sign.gd). Base stub = visual only.', "",
         f'[ext_resource type="PackedScene" path="{pre}{name}.glb" id="1_model"]',
         f'[ext_resource type="PackedScene" path="{pre}sign_breakaway_base.glb" id="2_base"]',
         f'[ext_resource type="Script" path="{gd}" id="3_script"]', ""]
    for i, s in enumerate(shp): L += [f'[sub_resource type="BoxShape3D" id="Box_{i}"]', "size = Vector3(%.4f, %.4f, %.4f)" % tuple(s["size_godot"]), ""]
    L += ['[sub_resource type="BoxShape3D" id="Hit"]', "size = Vector3(1.05, 1.5, 1.05)", ""]
    L += [f'[node name="{name}" type="Node3D"]', "",
          '[node name="Base" parent="." instance=ExtResource("2_base")]', "transform = Transform3D(1, 0, 0, 0, 1, 0, 0, 0, 1, %.4f, 0, %.4f)" % (ax[0], ax[2]), "",
          '[node name="Post" type="RigidBody3D" parent="."]', f"mass = {d['mass_kg']}", "freeze = true", 'script = ExtResource("3_script")', "",
          '[node name="Model" parent="Post" instance=ExtResource("1_model")]', ""]
    for i, s in enumerate(shp):
        L += [f'[node name="Col_{s["name"]}" type="CollisionShape3D" parent="Post"]',
              "transform = Transform3D(1, 0, 0, 0, 1, 0, 0, 0, 1, %.4f, %.4f, %.4f)" % tuple(s["centre_godot"]), f'shape = SubResource("Box_{i}")', ""]
    L += ['[node name="HitZone" type="Area3D" parent="Post"]', "transform = Transform3D(1, 0, 0, 0, 1, 0, 0, 0, 1, %.4f, 0.75, %.4f)" % (ax[0], ax[2]), "",
          '[node name="Shape" type="CollisionShape3D" parent="Post/HitZone"]', 'shape = SubResource("Hit")', ""]
    open(os.path.join(out, name + "_breakaway.tscn"), "w").write("\n".join(L)); n += 1
print("SCENES", n)
